    # Границы частей суток: [начало, конец) по часам.
    _PART_OF_DAY = ((5, 12, "morning"), (12, 18, "day"),
                    (18, 23, "evening"), (23, 24, "night"), (0, 5, "night"))

    @classmethod
    def part_of_day(cls, hour: int) -> str:
        """Часть суток по часу: morning | day | evening | night."""
        hour = int(hour) % 24
        for start, end, name in cls._PART_OF_DAY:
            if start <= hour < end:
                return name
        return "day"

    @classmethod
    def startup_greeting(cls, hour: int | None = None) -> str:
        """Приветствие при запуске: «Доброе утро, сэр...» по времени суток.

        Час можно передать явно — так это проверяется в тестах.
        """
        if hour is None:
            hour = datetime.now().hour
        return random.choice(cls._STARTUP[cls.part_of_day(hour)])

    @classmethod
    def get(cls, key: str, **kwargs) -> str:
        variants = cls._responses.get(key) or ["Готово, сэр."]
        text = random.choice(variants)
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text

    @classmethod
    def has(cls, key: str) -> bool:
        return key in cls._responses

    @classmethod
    def keys(cls) -> list:
        return sorted(cls._responses)
