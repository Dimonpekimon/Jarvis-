def intents_from_source() -> list:
    """Имена команд из реестра INTENTS — читаем исходник, а не импортируем.

    Импорт jarvis_core потянул бы за собой winrt (движок OCR экрана), а этот
    модуль капризен к порядку загрузки. Нам нужны только имена — хватит разбора
    исходного текста.
    """
    source = (BASE_DIR / "jarvis_core.py").read_text(encoding="utf-8")
    block = source.split("INTENTS = [", 1)[-1].split("\n]", 1)[0]
    return re.findall(r'Intent\("([a-z_]+)"', block)


