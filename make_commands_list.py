def main() -> int:
    parser = argparse.ArgumentParser(description="Список команд Джарвиса в текстовый файл")
    parser.add_argument("--stdout", action="store_true", help="показать, не записывая файл")
    args = parser.parse_args()

    text = build_text()

    # Сверка с кодом: список не должен разъезжаться с реестром команд.
    documented = {intent for _g, intent, _p, _d in COMMANDS if intent}
    actual = set(intents_from_source())
    missing = sorted(actual - documented)
    extra = sorted(documented - actual)
    if missing:
        print("[!] В коде есть команды, которых нет в списке: " + ", ".join(missing))
    if extra:
        print("[!] В списке есть команды, которых нет в коде: " + ", ".join(extra))
    if not missing and not extra:
        print(f"[ok] Сверка с кодом: все {len(actual)} команд описаны.")

    if args.stdout:
        print(text)
        return 0

    import config

    path = Path(config.COMMANDS_FILE)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"[ok] Файл записан: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
